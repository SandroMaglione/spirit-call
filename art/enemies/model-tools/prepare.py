def main(kind,source=None):
    here=ROOT/kind/'production'
    (here/'reference').mkdir(parents=True,exist_ok=True)
    (here/'renders').mkdir(exist_ok=True)
    (here/'.gitignore').write_text('*.blend1\n__pycache__/\nrenders/fit_*.png\n')
    if source:shutil.copyfile(source,here/'reference/sheet.png')
    config=CONFIGS[kind] | {'blend':f'{kind}-model.blend','background':'#DFDFE8',
        'ortho':1.5 if kind=='warden' else 1.25 if kind=='stalker' else 1.0,
        'resolution':[640,640],'ambient':.45,
        'lights':{'sun':[1.6,[1,.95,.9]],'fill':[.45,[.8,.88,1]],'rim':[.35,[1,1,1]]},
        'sweep':{'turns':[20,50,10],'elevations':[15,25,35]}}
    (here/'spirit.json').write_text(json.dumps(config,indent=2)+'\n')
    (here/'sheet.py').write_text('"""Re-measure the preserved enemy sheet."""\nimport sys\nfrom pathlib import Path\nsys.path.insert(0,str(Path(__file__).resolve().parents[2]/"model-tools"))\nfrom measure import measure\nmeasure("'+kind+'")\n')
    measure(kind)

