"""Register study exports and apply a reviewed arena layout without changing other looks."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LAYOUTS = Path(__file__).with_name("layouts.json")


def model_id(arena, asset):
    return arena + "Study" + "".join(word.title() for word in asset.split("-"))


def exports(layout):
    file = ROOT / "art/environment" / (layout["kit"] + "-study") / "manifest.json"
    return {a["id"]: a for a in json.loads(file.read_text())["assets"]}


def register(layouts):
    lines = ["/** Generated by art/environment/studies/integrate.py from verified export manifests. */",
             'import type { ModelSpec } from "../models.ts"']
    entries = []
    for arena, layout in layouts.items():
        for asset, item in exports(layout).items():
            key = model_id(arena, asset)
            lines.append(f'import {key}Url from "../../../art/environment/{layout["kit"]}-study/{item["file"]}?url"')
            width, height, depth = item["dimensions_m"]
            lo, hi = item["bounds_m"]["min"], item["bounds_m"]["max"]
            center = [(lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2]
            entries.append(f'  {key}: {{ url: {key}Url, height: {height:.8f}, footprint: [{width:.8f}, {depth:.8f}], footprintCenter: [{center[0]:.8f}, {center[1]:.8f}], clips: {{}} }}')
    lines += ["", "export const arenaPropModels = {", ",\n".join(entries), "} as const satisfies Record<string, ModelSpec>", ""]
    (ROOT / "src/presentation/assets/arena-props.ts").write_text("\n".join(lines))


def dimensions(item, quarter):
    x, _, z = item["dimensions_m"]
    return (z, x) if quarter % 2 else (x, z)


def turn(quarter):
    return ["0", "Math.PI / 2", "Math.PI", "3 * Math.PI / 2"][quarter % 4]


def replace_field(text, block_start, name, replacement):
    start = text.index(f"  {name}:", block_start)
    value = text.index("[", start)
    depth, cursor = 1, value + 1
    while depth:
        depth += (text[cursor] == "[") - (text[cursor] == "]")
        cursor += 1
    return text[:start] + replacement + text[cursor:]


def apply(arena, layout):
    manifest = exports(layout)
    boxes, props = [], []
    for placement in layout["props"]:
        asset, x, y, quarter, *edge = placement
        w, d = dimensions(manifest[asset], quarter)
        # Rounded boxes closely fit the model, with a little room around handles and foliage.
        w, d = math.ceil(w * 70 * 0.92 / 2) * 2, math.ceil(d * 70 * 0.92 / 2) * 2
        if edge:
            if edge[0] == "north": y = d / 2
            elif edge[0] == "south": y = 1800 - d / 2
            elif edge[0] == "west": x = w / 2
            elif edge[0] == "east": x = 1800 - w / 2
            elif edge[0] == "nw": x, y = w / 2, d / 2
            elif edge[0] == "ne": x, y = 1800 - w / 2, d / 2
            elif edge[0] == "sw": x, y = w / 2, 1800 - d / 2
            elif edge[0] == "se": x, y = 1800 - w / 2, 1800 - d / 2
            else: raise ValueError(edge)
        boxes.append(f"      prop({int(x)}, {int(y)}, {w}, {d})")
        props.append(f'    {{ model: "{model_id(arena, asset)}", turn: {turn(quarter)} }}')
    content_file = ROOT / "src/content/arena.ts"
    content = content_file.read_text()
    start = content.index(f"  {arena}: arena({{")
    content = replace_field(content, start, "props", "  props: [\n" + ",\n".join(boxes) + "\n    ]")
    if "pillars" in layout:
        pillars = [f'      {{ x: {x}, y: {y}, size: {size} }}' for x, y, size in layout["pillars"]]
        content = replace_field(content, start, "pillars", "  pillars: [\n" + ",\n".join(pillars) + "\n    ]")
    content_file.write_text(content)
    look_file = ROOT / "src/presentation/looks.ts"
    looks = look_file.read_text()
    start = looks.index(f"export const {arena}Arena: ArenaLook = {{")
    descriptions = {
        "courtyard": "Four stone pillars frame an open court, with low benches and planters for cover. Ritual goods dress the paving; a pergola, gate, alcove and fountain stand beyond the boundary.",
        "cistern": "The basins and low walls keep their water tactics. Compact machinery and repair benches provide cover; pump banks, valves and a settling tank fill the exterior service yard.",
        "kilnworks": "Fire trenches divide the foundry. Low casting benches and compact machinery interrupt its flanks; the furnace, chimney and covered work bays stand on the exterior paving.",
        "sanctuary": "Rooted saplings replace the corner pillars along the sanctuary's lanes. Low growth and fallen leaves dress the ground; rooted ruins and the shrine grove frame the exterior.",
        "harbor": "Cargo and moorings provide low cover around the harbor's water channels. Small dock gear lies on the boards; a supported crane, net shed and boat cradle stand outside the quay.",
        "necropolis": "The obelisk ring and elemental pools remain. Compact burial goods and folded-wing guardians provide cover; the tomb gate, burial dais and sun altar frame the burial ground.",
        "citadel": "A ring of four pillars surrounds the keep; banners and equipment racks mark the outer approaches. Small supplies dress the floor; a throne court and supported siege yard stand outside.",
        "monastery": "Low cloister walls retain their open corners. Benches, fitted lanterns and an attached bell provide cover; the bell tower, pavilion and winter hearth stand on the exterior paving."
    }
    doc_start = looks.rfind("/**", 0, start)
    looks = looks[:doc_start] + "/** " + descriptions[arena] + " */\n" + looks[start:]
    start = looks.index(f"export const {arena}Arena: ArenaLook = {{")
    scenery = [f'    {{ model: "{model_id(arena, asset)}", at: {{ x: {x}, y: {y} }}, turn: {turn(q)} }}' for asset, x, y, q in layout["scenery"]]
    looks = replace_field(looks, start, "scenery", "  scenery: [\n" + ",\n".join(scenery) + "\n  ]")
    looks = replace_field(looks, start, "props", "  props: [\n" + ",\n".join(props) + "\n  ]")
    # Every model placed outside the boundary stands on two extra rows of paving.
    floor = looks.index("  floor: {", start)
    if "apronTiles" not in looks[floor:looks.index("  walls:", floor)]:
        looks = looks[:floor] + looks[floor:].replace('    kind: "tiles",', '    kind: "tiles",\n    apronTiles: 2,', 1)
    if "  fires:" in looks[start:looks.index("\n}", start)]:
        flames = [f'    {{ at: {{ x: {x}, y: {y} }}, height: {h} }}' for x, y, h in layout.get("fires", [])]
        looks = replace_field(looks, start, "fires", "  fires: [\n" + ",\n".join(flames) + "\n  ]")
    look_file.write_text(looks)
    used = {p[0] for p in layout["props"] + layout["scenery"]}
    assert used == set(manifest), f"Missing exports: {set(manifest) - used}"
    print("INTEGRATED", arena, len(props), "blockers", len(scenery), "decorations and exterior pieces")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("arena", nargs="?")
    args = parser.parse_args()
    layouts = json.loads(LAYOUTS.read_text())
    if args.arena:
        apply(args.arena, layouts[args.arena])
    else:
        register(layouts)
