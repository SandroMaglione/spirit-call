"""Render the saved crow into the game's static directional atlas.

blender --background --python-exit-code 1 --python art/crow-study/bake-sprites.py
This reads crow.blend, including manual edits, without changing the source file.
"""
import json
import math
import tempfile
import sys
from pathlib import Path

import bpy
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Vector

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[1] / "src" / "presentation" / "assets"
OUTPUT.mkdir(parents=True, exist_ok=True)
ANIMATED = "--animated" in sys.argv
PREVIEW = "--preview" in sys.argv
bpy.ops.wm.open_mainfile(filepath=str(ROOT / ("crow-animated.blend" if ANIMATED else "crow.blend")))
scene = bpy.context.scene
root = bpy.data.objects["Crow | model root"]
camera = scene.camera
assert camera is not None

# Game +Y maps to Blender -Y. A 45-degree camera with sin(elevation)=0.5
# reproduces toScreen's (x-y, (x+y)*0.5) ground projection.
SQUASH = 0.5
ELEVATION = math.asin(SQUASH)
FRAME = 128 if ANIMATED else 256
COUNT = 16
COLUMNS = 4
ORTHO = 3.0
target = Vector((0, 0, 1.02))
camera.location = target + Vector((6 * math.cos(ELEVATION) / math.sqrt(2),
                                   -6 * math.cos(ELEVATION) / math.sqrt(2), 6 * SQUASH))
camera.rotation_euler = (target - camera.location).to_track_quat("-Z", "Y").to_euler()
camera.data.type = "ORTHO"
camera.data.ortho_scale = ORTHO
scene.render.resolution_x = scene.render.resolution_y = FRAME
scene.render.resolution_percentage = 100
scene.render.film_transparent = True
scene.render.image_settings.file_format = "PNG"
scene.render.image_settings.color_mode = "RGBA"
scene.cycles.samples = 24 if ANIMATED else 48
scene.cycles.use_denoising = True
scene.render.use_persistent_data = True
bpy.data.objects["Studio floor"].hide_render = True
bpy.context.view_layer.update()
origin = world_to_camera_view(scene, camera, Vector((0, 0, 0)))
meshes = [o for o in bpy.data.collections["CROW | editable character"].objects if o.type == "MESH"]
height = max((o.matrix_world @ v.co).z for o in meshes for v in o.data.vertices)

if ANIMATED:
    rig = bpy.data.objects["Crow rig | idle + run"]
    clips = {"idle": {"frames": 16, "sourceFrames": 48, "seconds": 2},
             "run": {"frames": 12, "sourceFrames": 12, "seconds": 0.5}}
    metadata = {
        "frameSize": FRAME, "columns": COUNT, "directions": COUNT,
        "anchor": {"x": round(origin.x, 8), "y": round(1 - origin.y, 8)},
        "projectedHeight": round(height * math.cos(ELEVATION) * FRAME / ORTHO, 8),
        "squash": SQUASH, "runDistance": 110, "clips": clips,
    }
    for clip, config in clips.items():
        rig.animation_data.action = bpy.data.actions[clip.title()]
        width, atlas_height = FRAME * COUNT, FRAME * config["frames"]
        pixels = [0.0] * (width * atlas_height * 4)
        directions = [0, 4, 8, 12] if PREVIEW else range(COUNT)
        with tempfile.TemporaryDirectory(prefix="crow-animation-") as temporary:
            for frame_index in range(config["frames"]):
                scene.frame_set(1 + frame_index * config["sourceFrames"] // config["frames"])
                for direction in directions:
                    root.rotation_euler.z = math.pi / 2 - direction * math.tau / COUNT
                    scene.render.filepath = str(Path(temporary) / "frame.png")
                    bpy.ops.render.render(write_still=True)
                    frame = bpy.data.images.load(scene.render.filepath, check_existing=False)
                    rgba = list(frame.pixels)
                    alpha = rgba[3::4]
                    assert max(alpha) > 0.9 and min(alpha) == 0
                    assert all(alpha[y * FRAME + x] == 0 for y in range(FRAME) for x in range(FRAME)
                               if x < 2 or y < 2 or x >= FRAME - 2 or y >= FRAME - 2), (clip, frame_index, direction)
                    left, bottom = direction * FRAME, atlas_height - (frame_index + 1) * FRAME
                    for row in range(FRAME):
                        at = ((bottom + row) * width + left) * 4
                        pixels[at:at + FRAME * 4] = rgba[row * FRAME * 4:(row + 1) * FRAME * 4]
                    bpy.data.images.remove(frame)
        atlas = bpy.data.images.new(f"Crow {clip} atlas", width=width, height=atlas_height, alpha=True)
        atlas.colorspace_settings.name = "sRGB"
        atlas.pixels.foreach_set(pixels)
        destination = ROOT / "renders" if PREVIEW else OUTPUT
        atlas.filepath_raw = str(destination / f"crow-{clip}{'-preview' if PREVIEW else ''}.png")
        atlas.file_format = "PNG"
        atlas.save()
        bpy.data.images.remove(atlas)
    if not PREVIEW:
        (OUTPUT / "crow-animation.ts").write_text(
            "// Generated by art/crow-study/bake-sprites.py -- --animated.\n"
            "// Columns are directions from world +X toward +Y; rows are animation frames.\n"
            "export const crowAnimation = " + json.dumps(metadata, indent=2) + " as const\n")
    print("CROW_ANIMATION_ATLASES", json.dumps(metadata))
    sys.exit(0)

size = FRAME * COLUMNS
pixels = [0.0] * (size * size * 4)
with tempfile.TemporaryDirectory(prefix="crow-sprites-") as temporary:
    for index in range(COUNT):
        # Frame zero faces game +X. Increasing indices turn toward game +Y.
        root.rotation_euler.z = math.pi / 2 - index * math.tau / COUNT
        scene.render.filepath = str(Path(temporary) / f"{index:02d}.png")
        bpy.ops.render.render(write_still=True)
        frame = bpy.data.images.load(scene.render.filepath, check_existing=False)
        rgba = list(frame.pixels)
        assert len(rgba) == FRAME * FRAME * 4
        alpha = rgba[3::4]
        assert max(alpha) > 0.9 and min(alpha) == 0, "Expected an opaque character on transparent pixels"
        # Keep transparent margins, so sampling cannot pick up a neighbor.
        assert all(alpha[y * FRAME + x] == 0 for y in range(FRAME)
                   for x in range(FRAME) if x < 2 or y < 2 or x >= FRAME - 2 or y >= FRAME - 2)
        left = (index % COLUMNS) * FRAME
        bottom = size - (index // COLUMNS + 1) * FRAME
        for row in range(FRAME):
            at = ((bottom + row) * size + left) * 4
            pixels[at:at + FRAME * 4] = rgba[row * FRAME * 4:(row + 1) * FRAME * 4]
        bpy.data.images.remove(frame)

atlas = bpy.data.images.new("Crow directional atlas", width=size, height=size, alpha=True)
atlas.colorspace_settings.name = "sRGB"
atlas.pixels.foreach_set(pixels)
atlas.filepath_raw = str(OUTPUT / "crow.png")
atlas.file_format = "PNG"
atlas.save()
metadata = {
    "frameSize": FRAME,
    "columns": COLUMNS,
    "directions": COUNT,
    "anchor": {"x": round(origin.x, 8), "y": round(1 - origin.y, 8)},
    "projectedHeight": round(height * math.cos(ELEVATION) * FRAME / ORTHO, 8),
    "squash": SQUASH,
}
(OUTPUT / "crow.ts").write_text(
    "// Generated by art/crow-study/bake-sprites.py from crow.blend.\n"
    "// Frames advance from world +X toward +Y; the anchor is the ground origin.\n"
    "export const crowAtlas = " + json.dumps(metadata, indent=2) + " as const\n"
)
print("CROW_ATLAS", json.dumps(metadata))
