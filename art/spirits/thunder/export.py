"""Export the approved Thunder model and its clips, then generate its spec.

The game scales by the whole figure's top above its ground origin, including
the crest and halo, to match Water's arena height. The source stays in rest pose.
"""
import hashlib
import json
import sys
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import animate

bpy.ops.wm.open_mainfile(filepath=str(HERE / "thunder-spirit.blend"))
bpy.context.view_layer.update()
height = max((o.matrix_world @ v.co).z
             for o in bpy.data.objects if o.type == "MESH"
             for v in o.data.vertices)
# Vertex-color emission exports as white. Keep the facet colors on the
# base and use a flat violet emission; the game supplies the edge glow.
violet = bpy.data.materials["Violet facets"]
bsdf = violet.node_tree.nodes["Principled BSDF"]
for link in list(bsdf.inputs["Emission Color"].links):
    violet.node_tree.links.remove(link)
bsdf.inputs["Emission Color"].default_value = (0.19, 0.147, 1.0, 1)  # #7A6BFF, linear
bsdf.inputs["Emission Strength"].default_value = 0.18
timing = animate.add_clips()
out = HERE / "thunder-spirit.glb"
bpy.ops.export_scene.gltf(
    filepath=str(out), export_format="GLB", export_apply=True,
    export_vertex_color="ACTIVE", export_attributes=True, export_animations=True,
    export_animation_mode="NLA_TRACKS", export_force_sampling=True,
    export_cameras=False, export_lights=False,
)
spec = HERE.parents[2] / "src" / "presentation" / "assets" / "thunder-spirit.ts"
spec.write_text(f'''// Generated by art/spirits/thunder/export.py. Edit the Blender source and re-export.
/** The thunder spirit: its loops (hovering, gliding) and combat clips (art/spirits/tools/moves.py), keyed on its objects. */
import type {{ ModelSpec }} from "../models.ts"
import thunderSpiritUrl from "../../../art/spirits/thunder/thunder-spirit.glb?url"

export const thunderSpiritModel = {{ url: thunderSpiritUrl, height: {height:.4f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
''')
metadata = {
    "source_sha256": hashlib.sha256((HERE / "thunder-spirit.blend").read_bytes()).hexdigest(),
    "glb_sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
    "bytes": out.stat().st_size, "height_m": height,
    "height_basis": "ground origin to highest rest-pose mesh vertex, including floating parts",
    "clips": timing,
    "triangles": sum(len(p.vertices) - 2 for o in bpy.data.objects if o.type == "MESH" for p in o.data.polygons),
}
(HERE / "export.json").write_text(json.dumps(metadata, indent=2) + "\n")
print(json.dumps(metadata))
