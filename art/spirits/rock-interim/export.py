"""Bastion's interim rock spirit: the static model under review, given loops and combat clips.

`static.glb` is the Rock Spirit as committed for model review (branch
art/rock-spirit-static, 38470d1), untouched. This imports it, keys a heavy,
grounded idle and a waddling run on its objects, adds the combat clips
every spirit shares (tools/moves.py), and exports `rock-spirit.glb` and its
spec for the game. It stands in until the reviewed spirit is animated in
art/spirits/rock; then this folder goes.

Run: Blender --background --python art/spirits/rock-interim/export.py
"""
import json
import math
import sys
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "tools"))
import moves  # noqa: E402

FPS = 30
# Bastion throws her discs from a planted stance: a small wind and turn, no hop, a heavy roll; her big throws spin.
STYLE = {"lunge": 0.02, "back": 0.03, "twist": 0.45, "roll": 0.1, "hop": 0.0, "spin": True, "cast": 0.1}
BODY = "RockSpirit"
FLOATS = ("TopRock", "Float.L", "Float.R")
FEET = ("Foot.L", "Foot.R")


def wave(t, phase=0.0):
    return math.sin(2 * math.pi * t + phase)


def pose(t, base, running):
    """A loop's pose at `t` (0 to 1): breathing and floating stones standing; a heavy waddle running."""
    bob = wave(t)
    # A blink near the end of the idle loop.
    shut = 0 if running else max(0, 1 - abs((t - 0.7) * 60) / 3)
    step = wave(t * 2) if running else 0.0
    values = {
        BODY: {
            "location": (0, 0, abs(wave(t)) * 0.012 if running else 0.003 * (1 + bob)),
            "rotation_euler": (0.1 if running else 0.0, 0.07 * wave(t) if running else 0.01 * wave(t, 0.6), 0),
            "scale": (1 + 0.01 * bob, 1 + 0.01 * bob, 1 - 0.015 * bob),
        }
    }
    for name, place in base.items():
        if name == BODY:
            continue
        x, y, z = place["location"]
        if name.startswith("Eye."):
            values[name] = {"scale": (1, 1, 1 - 0.9 * shut)}
        elif name in FLOATS:
            phase = {"TopRock": 0.0, "Float.L": 1.3, "Float.R": 2.6}[name]
            lag = 0.02 if running else 0.0
            values[name] = {
                "location": (x, y + lag, z + 0.012 * wave(t, phase)),
                "rotation_euler": (0.05 * wave(t, phase + 0.5), 0.05 * wave(t, phase), 0.3 * t if name != "TopRock" else 0.04 * wave(t, phase)),
            }
        elif name in FEET:
            side = 1 if name.endswith(".L") else -1
            lift = max(0.0, side * wave(t)) * 0.035 if running else 0.0
            values[name] = {"location": (x, y - (side * wave(t)) * 0.02 if running else y, z + lift)}
        else:
            values[name] = {"location": (x, y, z)}
    return values


def key_loop(objects, base, clip, frames, running):
    for name, obj in objects.items():
        obj.animation_data_create()
        action = bpy.data.actions.new(f"{clip}.{name}")
        obj.animation_data.action = action
        for frame in range(frames):
            for prop, value in pose(frame / frames, base, running)[name].items():
                setattr(obj, prop, value)
                obj.keyframe_insert(prop, frame=frame)
        track = obj.animation_data.nla_tracks.new()
        track.name = clip
        track.strips.new(clip, 0, action)
        track.mute = True
        obj.animation_data.action = None


bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(HERE / "static.glb"))
objects = {o.name: o for o in bpy.data.objects if o.type == "MESH"}
for obj in objects.values():
    obj.rotation_mode = "XYZ"
bpy.context.view_layer.update()
height = max((o.matrix_world @ v.co).z for o in objects.values() for v in o.data.vertices)
base = {name: {"location": tuple(o.location), "rotation_euler": tuple(o.rotation_euler), "scale": tuple(o.scale)} for name, o in objects.items()}

timing = {}
for clip, frames in (("Idle", 72), ("Run", 20)):
    key_loop(objects, base, clip, frames, clip == "Run")
    timing[clip] = {"lastKeySeconds": (frames - 1) / FPS, "loopSeconds": frames / FPS}
timing.update(moves.add(bpy, objects, base, BODY, STYLE))
for name, obj in objects.items():
    for prop, value in base[name].items():
        setattr(obj, prop, value)
bpy.context.scene.render.fps = FPS
bpy.context.view_layer.update()

out = HERE / "rock-spirit.glb"
bpy.ops.export_scene.gltf(
    filepath=str(out), export_format="GLB", export_apply=True,
    export_animations=True, export_animation_mode="NLA_TRACKS", export_force_sampling=True,
    export_cameras=False, export_lights=False,
)
spec = HERE.parents[2] / "src" / "presentation" / "assets" / "rock-spirit.ts"
spec.write_text(f'''// Generated by art/spirits/rock-interim/export.py. Re-run it after changing the script.
/** Bastion's interim rock spirit: the static model under review, with its loops (grounded, waddling) and combat clips (art/spirits/tools/moves.py), keyed on its objects. */
import type {{ ModelSpec }} from "../models.ts"
import rockSpiritUrl from "../../../art/spirits/rock-interim/rock-spirit.glb?url"

export const rockSpiritModel = {{ url: rockSpiritUrl, height: {height:.4f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
''')
print(json.dumps({"height": height, "clips": timing, "objects": list(objects)}))
