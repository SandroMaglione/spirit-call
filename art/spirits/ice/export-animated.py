"""Preserve the static source; export the complete game-compatible object clips."""
import hashlib
import json
import sys
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
import animate

bpy.ops.wm.open_mainfile(filepath=str(HERE/"ice-spirit.blend"))
timing,base = animate.add_clips()
bpy.context.preferences.filepaths.save_version=0
bpy.context.scene["stage"]="Animated spirit asset: ten object clips, no skeleton or root travel"
bpy.context.scene["native_axes"]="meters; Z up; -Y forward; static source remains +Y forward"
bpy.ops.wm.save_as_mainfile(filepath=str(HERE/"ice-spirit-animated.blend"))
out = HERE/"ice-spirit-animated.glb"
bpy.ops.export_scene.gltf(filepath=str(out),export_format="GLB",use_selection=True,
    export_animations=True,export_animation_mode="NLA_TRACKS",export_force_sampling=True,
    export_optimize_animation_keep_anim_object=True,
    export_frame_range=False,export_cameras=False,export_lights=False,
    export_texcoords=False,export_normals=True,export_yup=True,export_extras=True,
    export_materials="EXPORT",export_attributes=True,export_all_vertex_colors=True)
static = json.loads((HERE/"export.json").read_text())
metadata = {**static,"stage":"animated","native_axes":"meters, +Z up, -Y forward",
            "file":out.name,"clips":timing,"contacts":{k:v/30 for k,v in animate.moves.CONTACT.items()},
            "sha256":hashlib.sha256(out.read_bytes()).hexdigest(),"bytes":out.stat().st_size,
            "static_source_sha256":hashlib.sha256((HERE/"ice-spirit.blend").read_bytes()).hexdigest(),
            "style":animate.STYLE,"animation_base":base,"animations":len(timing)}
# The animation source faces -Y and has parent-relative child pivots.
# Replace the static source's +Y-facing world coordinates in this manifest.
bpy.context.view_layer.update()
metadata["objects"] = [{**item,
    "native_pivot_m":list(bpy.data.objects[item["name"]].matrix_world.translation),
    "local_pivot_m":list(bpy.data.objects[item["name"]].location),
    "parent":bpy.data.objects[item["name"]].parent.name if bpy.data.objects[item["name"]].parent else None,
} for item in static["objects"]]
(HERE/"animation.json").write_text(json.dumps(metadata,indent=2)+"\n")
spec = HERE.parents[2]/"src/presentation/assets/ice-spirit.ts"
spec.write_text(f'''// Generated by art/spirits/ice/export-animated.py. Re-export to change timing.
import type {{ ModelSpec }} from "../models.ts"
import iceSpiritUrl from "../../../art/spirits/ice/ice-spirit-animated.glb?url"

export const iceSpiritModel = {{ url: iceSpiritUrl, height: {static['height_m']:.8f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
''')
print(json.dumps({"file":out.name,"triangles":static["triangles"],"clips":timing,"bytes":out.stat().st_size},indent=2))
