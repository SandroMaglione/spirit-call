"""Exports the water spirit as a GLB for the game, with its clips (animate.py): facing +Z, +Y up, its origin on the floor under it.

Also writes `src/presentation/assets/water-spirit.ts`: the model's spec
(its file, its height with the nub, and its clips' timing).

    blender --background --python-exit-code 1 --python art/spirits/water/export.py
"""
from pathlib import Path

import json
import sys

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import animate  # noqa: E402
bpy.ops.wm.open_mainfile(filepath=str(HERE / "water-spirit.blend"))
# glTF has no glow in each facet's own color (the renders' soft inner
# glow): it would export as a flat white glow that washes the blues out.
# The game gets a gentle glow in the sheet's base blue instead.
water = bpy.data.materials["Water"]
bsdf = water.node_tree.nodes["Principled BSDF"]
for link in list(bsdf.inputs["Emission Color"].links):
    water.node_tree.links.remove(link)
bsdf.inputs["Emission Color"].default_value = (0.027, 0.2, 1.0, 1)  # #2E7BFF, linear
bsdf.inputs["Emission Strength"].default_value = 0.18
out = HERE / "water-spirit.glb"
height = max((o.matrix_world @ v.co).z for o in bpy.data.objects if o.type == "MESH" for v in o.data.vertices)
timing = animate.add_clips()
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", export_apply=True, export_vertex_color="ACTIVE", export_attributes=True,
                          export_animations=True, export_animation_mode="NLA_TRACKS", export_force_sampling=True)
tris = sum(len(p.vertices) - 2 for o in bpy.data.objects if o.type == "MESH" for p in o.data.polygons)
spec = HERE.parents[2] / "src" / "presentation" / "assets" / "water-spirit.ts"
spec.write_text(f"""// Generated by art/spirits/water/export.py. Edit the Blender source and re-export.
/** The water spirit: an idle and a run (art/spirits/water/animate.py); no attacks yet. */
import type {{ ModelSpec }} from "../models.ts"
import waterSpiritUrl from "../../../art/spirits/water/water-spirit.glb?url"

export const waterSpiritModel = {{ url: waterSpiritUrl, height: {height:.4f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
""")
print(f"exported {out.name}: {out.stat().st_size // 1024} KB, {tris} triangles, {height:.3f} m tall")
