"""Exports the fire spirit as a GLB for the game, with its clips (animate.py): facing +Z, +Y up, its origin on the floor under it.

Also writes `src/presentation/assets/fire-spirit.ts`: the model's spec
(its file, its flame's height, and its clips' timing).

glTF keeps the facets' colors but not the material's glow from within (its
yellow core facing the camera, its ember edges, which depend on the view):
the game adds those (`fireGlow` in `models.ts`); the file carries a flat
warm glow.

    blender --background --python-exit-code 1 --python art/spirits/fire/export.py
"""
import json
import sys
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import animate  # noqa: E402

bpy.ops.wm.open_mainfile(filepath=str(HERE / "fire-spirit.blend"))
fire = bpy.data.materials["Fire"]
nodes, links = fire.node_tree.nodes, fire.node_tree.links
bsdf = nodes["Principled BSDF"]
colors = next(n for n in nodes if n.type == "VERTEX_COLOR")
for socket in ("Base Color", "Emission Color"):
    for link in list(bsdf.inputs[socket].links):
        links.remove(link)
links.new(colors.outputs["Color"], bsdf.inputs["Base Color"])
bsdf.inputs["Emission Color"].default_value = (1.0, 0.25, 0.04, 1)  # #FF8A3D, linear
bsdf.inputs["Emission Strength"].default_value = 0.35
out = HERE / "fire-spirit.glb"
# Its height for the game: the flame's (the floating shards above it don't count), so its body is as big as the other spirits'.
body = bpy.data.objects["FireSpirit"]
height = max((body.matrix_world @ v.co).z for v in body.data.vertices)
timing = animate.add_clips()
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", export_apply=True, export_vertex_color="ACTIVE", export_attributes=True,
                          export_animations=True, export_animation_mode="NLA_TRACKS", export_force_sampling=True)
tris = sum(len(p.vertices) - 2 for o in bpy.data.objects if o.type == "MESH" for p in o.data.polygons)
spec = HERE.parents[2] / "src" / "presentation" / "assets" / "fire-spirit.ts"
spec.write_text(f"""// Generated by art/spirits/fire/export.py. Edit the Blender source and re-export.
/** The fire spirit: an idle and a run (art/spirits/fire/animate.py); no attacks yet. */
import type {{ ModelSpec }} from "../models.ts"
import fireSpiritUrl from "../../../art/spirits/fire/fire-spirit.glb?url"

export const fireSpiritModel = {{ url: fireSpiritUrl, height: {height:.4f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
""")
print(f"exported {out.name}: {out.stat().st_size // 1024} KB, {tris} triangles, {height:.3f} m tall")
