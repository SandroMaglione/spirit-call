"""Generate the game's model spec from the delivered animation metadata."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def write_spec():
    metadata = json.loads((HERE / "animation.json").read_text())
    spec = HERE.parents[3] / "src/presentation/assets/quarry-spirit.ts"
    spec.write_text(f'''// Generated by art/spirits/rock/quarry/export.py. Re-export to change timing.
import type {{ ModelSpec }} from "../models.ts"
import quarrySpiritUrl from "../../../art/spirits/rock/quarry/quarry-animated.glb?url"

export const quarrySpiritModel = {{ url: quarrySpiritUrl, height: {metadata['height_m']:.8f}, clips: {json.dumps(metadata['clips'])} }} as const satisfies ModelSpec
''')


if __name__ == "__main__":
    write_spec()
