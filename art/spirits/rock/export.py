"""Export the accepted rest model with object clips and generate its game spec."""
import hashlib
import json
import sys
from pathlib import Path
import bpy

HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
import animate
bpy.ops.wm.open_mainfile(filepath=str(HERE/"rock-spirit.blend"))
timing=animate.add_clips()
# Preserve the accepted rest source and save a separate editable animated file.
bpy.ops.wm.save_as_mainfile(filepath=str(HERE/"rock-spirit-animated.blend"))
out=HERE/"rock-spirit.glb"
bpy.ops.export_scene.gltf(filepath=str(out),export_format="GLB",export_apply=True,
    export_vertex_color="ACTIVE",export_animations=True,export_animation_mode="NLA_TRACKS",
    export_force_sampling=True,export_cameras=False,export_lights=False)
audit=json.loads((HERE/"audit.json").read_text())
metadata={**audit,"status":"animated game export","animations":len(timing),"bytes":out.stat().st_size,"source_sha256":hashlib.sha256((HERE/"rock-spirit.blend").read_bytes()).hexdigest(),"glb_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),"clips":timing}
(HERE/"export.json").write_text(json.dumps(metadata,indent=2)+"\n")
spec=HERE.parents[2]/"src/presentation/assets/rock-spirit.ts"
spec.write_text(f'''// Generated by art/spirits/rock/export.py. Re-export to change timing.
import type {{ ModelSpec }} from "../models.ts"
import rockSpiritUrl from "../../../art/spirits/rock/rock-spirit.glb?url"

export const rockSpiritModel = {{ url: rockSpiritUrl, height: {audit['height_m']:.8f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
''')
print(json.dumps(metadata))
