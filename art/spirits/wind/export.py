"""Exports the wind spirit as a GLB for the game, with its clips (animate.py): facing +Z, +Y up, its origin on the floor under it.

Also writes `src/presentation/assets/wind-spirit.ts`: the model's spec
(its file, its height, and its clips' timing).

glTF has no glow in each facet's own color (the renders' soft inner glow):
it would export as a flat white glow that washes the mints out. The file
carries a gentle glow in the sheet's pale aqua; the rest is the game's
(`windGlow` in `models.ts`).

    blender --background --python-exit-code 1 --python art/spirits/wind/export.py
"""
import json
import sys
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import animate  # noqa: E402

bpy.ops.wm.open_mainfile(filepath=str(HERE / "wind-spirit.blend"))
wind = bpy.data.materials["Wind"]
bsdf = wind.node_tree.nodes["Principled BSDF"]
for link in list(bsdf.inputs["Emission Color"].links):
    wind.node_tree.links.remove(link)
bsdf.inputs["Emission Color"].default_value = (0.52, 0.86, 0.73, 1)  # #BFEFDF, linear
bsdf.inputs["Emission Strength"].default_value = 0.15
out = HERE / "wind-spirit.glb"
# Its height for the game: the whole figure's, top leaf included (its leaves and horns grow from it, nothing floats above
# it), so it stands as tall as the other spirits.
height = max((o.matrix_world @ v.co).z for o in bpy.data.objects if o.type == "MESH" for v in o.data.vertices)
timing = animate.add_clips()
bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", export_apply=True, export_vertex_color="ACTIVE", export_attributes=True,
                          export_animations=True, export_animation_mode="NLA_TRACKS", export_force_sampling=True)
tris = sum(len(p.vertices) - 2 for o in bpy.data.objects if o.type == "MESH" for p in o.data.polygons)
spec = HERE.parents[2] / "src" / "presentation" / "assets" / "wind-spirit.ts"
spec.write_text(f"""// Generated by art/spirits/wind/export.py. Edit the Blender source and re-export.
/** The wind spirit: an idle and a run (art/spirits/wind/animate.py); no attacks yet. */
import type {{ ModelSpec }} from "../models.ts"
import windSpiritUrl from "../../../art/spirits/wind/wind-spirit.glb?url"

export const windSpiritModel = {{ url: windSpiritUrl, height: {height:.4f}, clips: {json.dumps(timing)} }} as const satisfies ModelSpec
""")
print(f"exported {out.name}: {out.stat().st_size // 1024} KB, {tris} triangles, {height:.3f} m tall")
